-- Week 2 ETL implementation scaffold. PostgreSQL 14+.
-- Run in the same database as the Week 1 project.
-- This script creates an etl schema plus raw staging, reject, and batch audit tables.
BEGIN;
CREATE SCHEMA IF NOT EXISTS etl;

CREATE TABLE IF NOT EXISTS etl.etl_batch (
    batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name TEXT NOT NULL,
    source_file TEXT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    batch_status TEXT NOT NULL DEFAULT 'running'
        CHECK (batch_status IN ('running','succeeded','failed','completed_with_rejects')),
    extracted_rows INTEGER NOT NULL DEFAULT 0,
    accepted_rows INTEGER NOT NULL DEFAULT 0,
    rejected_rows INTEGER NOT NULL DEFAULT 0,
    inserted_rows INTEGER NOT NULL DEFAULT 0,
    updated_rows INTEGER NOT NULL DEFAULT 0,
    error_message TEXT
);

CREATE TABLE IF NOT EXISTS etl.stg_customers (
    staging_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES etl.etl_batch(batch_id),
    source_customer_id TEXT,
    first_name TEXT,
    last_name TEXT,
    email TEXT,
    phone TEXT,
    city TEXT,
    state TEXT,
    country_code TEXT,
    updated_at_text TEXT,
    raw_record JSONB NOT NULL DEFAULT '{}'::jsonb,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS etl.stg_products (
    staging_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES etl.etl_batch(batch_id),
    source_product_id TEXT,
    sku TEXT,
    product_name TEXT,
    category_name TEXT,
    unit_price_text TEXT,
    currency_code TEXT,
    updated_at_text TEXT,
    raw_record JSONB NOT NULL DEFAULT '{}'::jsonb,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS etl.stg_orders (
    staging_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES etl.etl_batch(batch_id),
    source_order_id TEXT,
    order_number TEXT,
    source_customer_id TEXT,
    order_status TEXT,
    order_date_text TEXT,
    subtotal_text TEXT,
    discount_amount_text TEXT,
    tax_amount_text TEXT,
    shipping_amount_text TEXT,
    total_amount_text TEXT,
    currency_code TEXT,
    raw_record JSONB NOT NULL DEFAULT '{}'::jsonb,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS etl.etl_reject (
    reject_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES etl.etl_batch(batch_id),
    source_entity TEXT NOT NULL,
    source_key TEXT,
    reject_reason TEXT NOT NULL,
    raw_record JSONB NOT NULL DEFAULT '{}'::jsonb,
    rejected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ
);

COMMIT;
