-- Low-stock alert table and trigger (PostgreSQL).
-- This records a low-stock event when quantity crosses from above the threshold
-- to at-or-below the threshold. It does not send email or external notifications.

CREATE TABLE IF NOT EXISTS inventory_alerts (
    alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    stock_quantity INTEGER NOT NULL,
    threshold_quantity INTEGER NOT NULL,
    alert_message TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolved_at TIMESTAMPTZ
);

CREATE OR REPLACE FUNCTION record_low_stock_alert()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_threshold CONSTANT INTEGER := 10;
BEGIN
    IF NEW.stock_quantity <= v_threshold
       AND (TG_OP = 'INSERT'
            OR OLD.stock_quantity > v_threshold) THEN
        INSERT INTO inventory_alerts (
            product_id, stock_quantity, threshold_quantity, alert_message
        )
        VALUES (
            NEW.product_id,
            NEW.stock_quantity,
            v_threshold,
            format('Low stock: product %s has %s units remaining',
                   NEW.product_id, NEW.stock_quantity)
        );
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_record_low_stock_alert ON products;

CREATE TRIGGER trg_record_low_stock_alert
AFTER INSERT OR UPDATE OF stock_quantity
ON products
FOR EACH ROW
EXECUTE FUNCTION record_low_stock_alert();

