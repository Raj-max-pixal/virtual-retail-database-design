-- Virtual Retail Database Design
-- PostgreSQL 14+
-- Run this script in a NEW database. It drops/recreates the project schema.

BEGIN;

DROP SCHEMA IF EXISTS retail CASCADE;
CREATE SCHEMA retail;
SET search_path TO retail, public;

CREATE TABLE customers (
    customer_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name       VARCHAR(80) NOT NULL,
    last_name        VARCHAR(80) NOT NULL,
    email            VARCHAR(255) NOT NULL UNIQUE,
    phone            VARCHAR(30),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT customers_email_not_blank CHECK (BTRIM(email) <> '')
);

CREATE TABLE customer_addresses (
    address_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      BIGINT NOT NULL REFERENCES customers(customer_id) ON DELETE CASCADE,
    address_type     VARCHAR(20) NOT NULL DEFAULT 'shipping',
    recipient_name   VARCHAR(160) NOT NULL,
    address_line1    VARCHAR(200) NOT NULL,
    address_line2    VARCHAR(200),
    city             VARCHAR(100) NOT NULL,
    state_region     VARCHAR(100),
    postal_code      VARCHAR(20),
    country_code     CHAR(2) NOT NULL,
    is_default       BOOLEAN NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT address_type_valid CHECK (address_type IN ('billing', 'shipping', 'both'))
);

CREATE TABLE categories (
    category_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name    VARCHAR(120) NOT NULL UNIQUE,
    description      TEXT,
    parent_category_id BIGINT REFERENCES categories(category_id) ON DELETE SET NULL
);

CREATE TABLE products (
    product_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku              VARCHAR(64) NOT NULL UNIQUE,
    product_name     VARCHAR(200) NOT NULL,
    description      TEXT,
    category_id      BIGINT REFERENCES categories(category_id) ON DELETE SET NULL,
    unit_price       NUMERIC(12,2) NOT NULL,
    currency_code    CHAR(3) NOT NULL DEFAULT 'INR',
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT product_price_nonnegative CHECK (unit_price >= 0)
);

CREATE TABLE inventory (
    product_id       BIGINT PRIMARY KEY REFERENCES products(product_id) ON DELETE RESTRICT,
    quantity_on_hand INTEGER NOT NULL DEFAULT 0,
    reorder_level    INTEGER NOT NULL DEFAULT 5,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT inventory_quantity_nonnegative CHECK (quantity_on_hand >= 0),
    CONSTRAINT inventory_reorder_nonnegative CHECK (reorder_level >= 0)
);

CREATE TABLE customer_orders (
    order_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number      VARCHAR(40) NOT NULL UNIQUE,
    customer_id       BIGINT NOT NULL REFERENCES customers(customer_id) ON DELETE RESTRICT,
    order_status      VARCHAR(20) NOT NULL DEFAULT 'pending',
    order_date        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    currency_code     CHAR(3) NOT NULL DEFAULT 'INR',
    subtotal          NUMERIC(12,2) NOT NULL DEFAULT 0,
    discount_amount   NUMERIC(12,2) NOT NULL DEFAULT 0,
    tax_amount        NUMERIC(12,2) NOT NULL DEFAULT 0,
    shipping_amount   NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_amount      NUMERIC(12,2) NOT NULL DEFAULT 0,
    -- Snapshot fields preserve the delivery address even if the customer's address changes.
    ship_to_name      VARCHAR(160),
    ship_to_line1     VARCHAR(200),
    ship_to_line2     VARCHAR(200),
    ship_to_city      VARCHAR(100),
    ship_to_state     VARCHAR(100),
    ship_to_postal    VARCHAR(20),
    ship_to_country   CHAR(2),
    CONSTRAINT order_status_valid CHECK
        (order_status IN ('pending','confirmed','processing','shipped','delivered','cancelled','refunded')),
    CONSTRAINT order_amounts_nonnegative CHECK
        (subtotal >= 0 AND discount_amount >= 0 AND tax_amount >= 0 AND shipping_amount >= 0 AND total_amount >= 0),
    CONSTRAINT order_total_consistent CHECK
        (total_amount = subtotal - discount_amount + tax_amount + shipping_amount)
);

CREATE TABLE order_items (
    order_item_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL REFERENCES customer_orders(order_id) ON DELETE CASCADE,
    product_id       BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    sku_snapshot     VARCHAR(64) NOT NULL,
    product_name_snapshot VARCHAR(200) NOT NULL,
    quantity         INTEGER NOT NULL,
    unit_price       NUMERIC(12,2) NOT NULL,
    discount_amount  NUMERIC(12,2) NOT NULL DEFAULT 0,
    line_total       NUMERIC(12,2) NOT NULL,
    CONSTRAINT order_item_quantity_positive CHECK (quantity > 0),
    CONSTRAINT order_item_amounts_nonnegative CHECK
        (unit_price >= 0 AND discount_amount >= 0 AND line_total >= 0),
    CONSTRAINT order_item_total_consistent CHECK
        (line_total = quantity * unit_price - discount_amount),
    CONSTRAINT order_item_product_once_per_order UNIQUE (order_id, product_id)
);

CREATE TABLE payments (
    payment_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL REFERENCES customer_orders(order_id) ON DELETE RESTRICT,
    payment_reference VARCHAR(100) UNIQUE,
    payment_method   VARCHAR(20) NOT NULL,
    payment_status   VARCHAR(20) NOT NULL DEFAULT 'initiated',
    amount           NUMERIC(12,2) NOT NULL,
    currency_code    CHAR(3) NOT NULL DEFAULT 'INR',
    paid_at          TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT payment_method_valid CHECK
        (payment_method IN ('card','upi','netbanking','wallet','cash_on_delivery','bank_transfer')),
    CONSTRAINT payment_status_valid CHECK
        (payment_status IN ('initiated','authorized','captured','failed','refunded','partially_refunded')),
    CONSTRAINT payment_amount_positive CHECK (amount > 0)
);

CREATE TABLE shipments (
    shipment_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL REFERENCES customer_orders(order_id) ON DELETE RESTRICT,
    carrier          VARCHAR(100),
    tracking_number  VARCHAR(120) UNIQUE,
    shipment_status  VARCHAR(20) NOT NULL DEFAULT 'pending',
    shipped_at       TIMESTAMPTZ,
    delivered_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT shipment_status_valid CHECK
        (shipment_status IN ('pending','packed','shipped','in_transit','delivered','returned','lost')),
    CONSTRAINT shipment_dates_valid CHECK
        (delivered_at IS NULL OR shipped_at IS NULL OR delivered_at >= shipped_at)
);

-- Append-only audit ledger: each stock adjustment should be recorded here.
CREATE TABLE inventory_movements (
    movement_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    movement_type    VARCHAR(20) NOT NULL,
    quantity_change  INTEGER NOT NULL,
    reference_type   VARCHAR(30),
    reference_id     BIGINT,
    note             TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT movement_type_valid CHECK
        (movement_type IN ('receipt','sale','return','adjustment','damage','reservation_release')),
    CONSTRAINT movement_quantity_nonzero CHECK (quantity_change <> 0)
);

-- Indexes for common joins, filters, and reports.
CREATE INDEX idx_addresses_customer ON customer_addresses(customer_id);
CREATE INDEX idx_products_category ON products(category_id);
CREATE INDEX idx_orders_customer_date ON customer_orders(customer_id, order_date DESC);
CREATE INDEX idx_orders_status_date ON customer_orders(order_status, order_date DESC);
CREATE INDEX idx_order_items_product ON order_items(product_id);
CREATE INDEX idx_payments_order_status ON payments(order_id, payment_status);
CREATE INDEX idx_shipments_order_status ON shipments(order_id, shipment_status);
CREATE INDEX idx_inventory_movements_product_date ON inventory_movements(product_id, created_at DESC);
CREATE INDEX idx_products_active_name ON products(product_name) WHERE is_active = TRUE;

COMMIT;
